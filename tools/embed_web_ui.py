#!/usr/bin/env python3
"""Embed the dependency-free Web UI into the mb-capture binary.

The board installs only executables, so the browser assets are generated into a
C++ header at build time.  The checked-in header keeps tools/build_on_board.sh
working on targets where Python is available but CMake is not.
"""

from pathlib import Path
import ast
import base64
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
UI = ROOT / "src" / "web" / "ui"
OUT = ROOT / "src" / "web" / "web_ui_generated.h"
ASSETS = [
    ("kIndexHtml", UI / "index.html", "HTML"),
    ("kWebCss", UI / "app.css", "CSS"),
    ("kWebJs", UI / "app.js", "JS"),
]
# Keep the web identity tied to the desktop application icon rather than a
# separately maintained copy.
APP_ICON = ROOT / "app" / "icons" / "hicolor" / "128x128" / "apps" / "com.quectel.MonitorBox.png"
APP_I18N = ROOT / "app" / "mb_i18n.py"
WEB_I18N_EXTRA = UI / "i18n-en.json"
FONT_DIR = UI / "fonts"
FONT_LICENSE = FONT_DIR / "LICENSE.txt"
FONTS = [
    ("kWebFontNotoSansSc400", FONT_DIR / "noto-sans-sc-400.woff2"),
    ("kWebFontNotoSansSc600", FONT_DIR / "noto-sans-sc-600.woff2"),
    ("kWebFontNotoSansSc700", FONT_DIR / "noto-sans-sc-700.woff2"),
    ("kWebFontNotoSansMono400", FONT_DIR / "noto-sans-mono-400.woff2"),
    ("kWebFontNotoSansMono700", FONT_DIR / "noto-sans-mono-700.woff2"),
]
for _weight in (400, 600, 700):
    for _slice in (102, 105, 109):
        FONTS.append((
            f"kWebFontNotoSansSc{_slice}{_weight}",
            FONT_DIR / f"noto-sans-sc-{_slice}-{_weight}-normal.woff2",
        ))


def literal(name: str, path: Path, suffix: str) -> str:
    text = path.read_text(encoding="utf-8")
    marker = f"MBUI_{suffix}"
    if len(marker) > 16:
        raise SystemExit(f"raw-string delimiter too long: {marker}")
    if f"){marker}\"" in text:
        raise SystemExit(f"{path}: embedded raw-string delimiter {marker} found in asset")
    return f'inline constexpr char {name}[] = R"{marker}({text}){marker}";\n'


def text_literal(name: str, text: str, suffix: str) -> str:
    marker = f"MBUI_{suffix}"
    if len(marker) > 16:
        raise SystemExit(f"raw-string delimiter too long: {marker}")
    if f"){marker}\"" in text:
        raise SystemExit(f"embedded raw-string delimiter {marker} found")
    return f'inline constexpr char {name}[] = R"{marker}({text}){marker}";\n'


def app_i18n_js() -> str:
    """Reuse the APP catalogue, then layer Web-only strings on top."""
    tree = ast.parse(APP_I18N.read_text(encoding="utf-8"))
    catalogue = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "_EN" for t in node.targets):
            catalogue = ast.literal_eval(node.value)
            break
    if not catalogue:
        raise SystemExit(f"{APP_I18N}: _EN catalogue not found")
    extra = json.loads(WEB_I18N_EXTRA.read_text(encoding="utf-8"))
    if not isinstance(extra, dict):
        raise SystemExit(f"{WEB_I18N_EXTRA}: expected a JSON object")
    catalogue.update(extra)
    payload = json.dumps(catalogue, ensure_ascii=False, separators=(",", ":"))
    return "window.MB_APP_I18N = " + payload + ";\n"


def base64_literal(name: str, path: Path) -> str:
    """Embed a font as wrapped base64 so the C++ source stays text-only."""
    encoded = base64.b64encode(path.read_bytes()).decode("ascii")
    lines = [encoded[i:i + 96] for i in range(0, len(encoded), 96)]
    body = "\n".join(f'    "{line}"' for line in lines)
    return (
        f"inline constexpr char {name}[] =\n{body};\n"
        f"inline constexpr std::size_t {name}Size = sizeof({name}) - 1;\n"
    )

def binary_literal(name: str, path: Path) -> str:
    data = path.read_bytes()
    rows = []
    for start in range(0, len(data), 16):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in data[start:start + 16]) + ",")
    return ("inline constexpr unsigned char " + name + "[] = {\n" + "\n".join(rows) +
            "\n};\ninline constexpr std::size_t " + name + "Size = sizeof(" + name + ");\n")


def main() -> None:
    parts = [
        "// Generated by tools/embed_web_ui.py. Do not edit by hand.\n",
        "#ifndef MONITOR_BOX_WEB_UI_GENERATED_H_\n",
        "#define MONITOR_BOX_WEB_UI_GENERATED_H_\n\n",
        "#include <cstddef>\n\n",
    ]
    parts.extend(literal(*asset) + "\n" for asset in ASSETS)
    parts.append(text_literal("kWebI18n", app_i18n_js(), "I18N") + "\n")
    parts.append(text_literal("kWebFontLicense",
                              FONT_LICENSE.read_text(encoding="utf-8"), "FLIC") + "\n")
    for name, path in FONTS:
        if not path.is_file():
            raise SystemExit(f"web font not found: {path}")
        parts.append(base64_literal(name, path) + "\n")
    parts.append(binary_literal("kAppIconPng", APP_ICON) + "\n")
    parts.append("#endif  // MONITOR_BOX_WEB_UI_GENERATED_H_\n")
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"embedded fonts ({len(FONTS)} files); {', '.join(a[1].name for a in ASSETS)} -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
