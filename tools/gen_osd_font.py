#!/usr/bin/env python3
"""Regenerate the embedded Cantarell OSD glyph table.

The board's GNOME settings override selects Cantarell 11 for the English UI.
OSD text must not depend on a desktop font stack at runtime, so this tool
rasterizes the printable ASCII range once and writes a compact grayscale atlas
that the capture binary links in.

Usage (from the SDK root):
    python3 projects/demo-monitor-box/tools/gen_osd_font.py

Pillow is only needed to regenerate the table, not to build or run monitor_box.
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[3]
FONT = ROOT / "prebuilds/sysroot/usr/share/fonts/opentype/cantarell/Cantarell-VF.otf"
OUTPUT = ROOT / "projects/demo-monitor-box/third_party/zoo/font.h"
EM = 40
CELL_WIDTH = 42
CELL_HEIGHT = 50
FIRST = 32
LAST = 126


def advance_px(font, ch):
    return max(0, int(round(font.getlength(ch))))


def main():
    if not FONT.is_file():
        raise SystemExit(f"Cantarell font not found: {FONT}")

    font = ImageFont.truetype(str(FONT), EM)
    glyphs = []
    advances = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advances.append(advance_px(font, ch))
        glyph = Image.new("L", (CELL_WIDTH, CELL_HEIGHT), 0)
        # x=1 keeps the leftmost bearing of '_' inside the atlas cell.
        ImageDraw.Draw(glyph).text((1, 0), ch, font=font, fill=255)
        glyphs.append(glyph)

    lines = [
        "// Generated by tools/gen_osd_font.py; do not edit by hand.",
        "// Rasterized from GNOME's default English UI font, Cantarell.",
        "// Cantarell is Copyright (c) 2009-2011 Understanding Limited and",
        "// Copyright (c) 2010-2011 Jakub Steiner; licensed under OFL-1.1.",
        "// See third_party/cantarell/LICENSE.",
        f"#define UI_FONT_EM {EM}",
        f"#define UI_FONT_CELL_WIDTH {CELL_WIDTH}",
        f"#define UI_FONT_CELL_HEIGHT {CELL_HEIGHT}",
        "",
        f"static const unsigned char ui_font_advance[{LAST - FIRST + 1}] = {{",
    ]
    lines.extend("    " + ", ".join(f"{value:3d}" for value in advances[i:i + 16]) + ","
                 for i in range(0, len(advances), 16))
    lines += ["};", "", f"static const unsigned char ui_font_data[{LAST - FIRST + 1}]"
              f"[UI_FONT_CELL_WIDTH * UI_FONT_CELL_HEIGHT] = {{"]
    for glyph in glyphs:
        data = list(glyph.tobytes())
        lines.append("    {")
        for i in range(0, len(data), CELL_WIDTH):
            row = data[i:i + CELL_WIDTH]
            lines.append("        " + ", ".join(f"0x{value:02x}" for value in row) + ",")
        lines.append("    },")
    lines += ["};", ""]
    OUTPUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
